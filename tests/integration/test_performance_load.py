        endpoints_sla = [
            ("/api/v1/auth/verify", "GET", 100),  # <100ms
            ("/api/v1/devices/search", "POST", 200),  # <200ms  
            ("/api/v1/documents/upload/presigned", "POST", 500),  # <500ms
            ("/api/v1/analytics/summary", "GET", 1000),  # <1s
        ]
        
        results = {}
        
        for endpoint, method, sla_ms in endpoints_sla:
            times = []
            
