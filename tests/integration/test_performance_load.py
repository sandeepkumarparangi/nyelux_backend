    @pytest.mark.asyncio
    async def test_concurrent_user_load(
        self, client: AsyncClient, db: AsyncSession, auth_tokens
    ):
        """Test system with concurrent users"""
        # Simulate 100 concurrent users (reduced from 10K for testing)
        concurrent_users = 100
        requests_per_user = 10
        
        async def user_session(token: str, user_id: int):
            """Simulate a user session"""
            headers = {"Authorization": f"Bearer {token}"}
            results = []
            
            for i in range(requests_per_user):
                # Mix of different operations
                operation = i % 5
                start = time.time()
                
                try:
                    if operation == 0:  # Search
                        response = await client.post(
                            "/api/v1/devices/search",
                            json={"query": f"device {user_id}"},
                            headers=headers
                        )
                    elif operation == 1:  # View device
                        response = await client.get(
                            f"/api/v1/devices/00889842{user_id:06d}",
                            headers=headers
                        )
                    elif operation == 2:  # Analytics
                        response = await client.get(
                            "/api/v1/analytics/summary",
                            headers=headers
                        )
                    elif operation == 3:  # Create note
                        response = await client.post(
                            "/api/v1/notes",
                            json={"content": f"Note from user {user_id}"},
                            headers=headers
                        )
                    else:  # List documents
                        response = await client.get(
                            "/api/v1/documents",
                            headers=headers
                        )
                    
                    elapsed = time.time() - start
                    results.append({
                        "operation": operation,
                        "status": response.status_code,
                        "time": elapsed,
                        "success": 200 <= response.status_code < 300
                    })
                    
                except Exception as e:
                    results.append({
                        "operation": operation,
                        "status": 0,
                        "time": time.time() - start,
                        "success": False,
                        "error": str(e)
                    })
                
                # Small delay between requests
                await asyncio.sleep(0.1)
            
            return results
        
        # Create tasks for concurrent users
        tasks = []
        for i in range(concurrent_users):
            token = auth_tokens[i % len(auth_tokens)]
            task = user_session(token, i)
            tasks.append(task)
        
        # Execute concurrently
        start_time = time.time()
        all_results = await asyncio.gather(*tasks)
        total_time = time.time() - start_time
        
        # Analyze results
        total_requests = 0
        successful_requests = 0
        response_times = []
        
        for user_results in all_results:
            for result in user_results:
                total_requests += 1
                if result["success"]:
                    successful_requests += 1
                    response_times.append(result["time"])
        
        success_rate = (successful_requests / total_requests) * 100
        avg_response_time = statistics.mean(response_times) if response_times else 0
        
        # Assertions
        assert success_rate > 99, f"Success rate {success_rate:.2f}% below 99%"
        assert avg_response_time < 1.0, f"Avg response time {avg_response_time:.2f}s exceeds 1s"
        
        # Calculate throughput
        throughput = total_requests / total_time
        print(f"\nConcurrent Load Test Results:")
        print(f"  Total requests: {total_requests}")
        print(f"  Success rate: {success_rate:.2f}%")
        print(f"  Avg response time: {avg_response_time:.3f}s")
        print(f"  Throughput: {throughput:.2f} req/s")

